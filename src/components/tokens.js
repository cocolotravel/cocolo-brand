// WCAG contrast helpers (hex only)
function hexToRgb(hex) {
  const h = hex.replace("#", "").trim();
  if (h.length !== 6) return null;
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
}
function lum(rgb) {
  const a = rgb.map((v) => {
    v /= 255;
    return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4);
  });
  return 0.2126 * a[0] + 0.7152 * a[1] + 0.0722 * a[2];
}
export function contrast(hex1, hex2) {
  const a = hexToRgb(hex1), b = hexToRgb(hex2);
  if (!a || !b) return null;
  const l1 = lum(a), l2 = lum(b);
  const [hi, lo] = l1 > l2 ? [l1, l2] : [l2, l1];
  return (hi + 0.05) / (lo + 0.05);
}
export function grade(ratio) {
  if (ratio == null) return { label: "—", pass: null };
  if (ratio >= 7) return { label: "AAA", pass: true };
  if (ratio >= 4.5) return { label: "AA", pass: true };
  if (ratio >= 3) return { label: "AA Lg", pass: true };
  return { label: "Fail", pass: false };
}

// ---------------------------------------------------------------------------
// Fluid scale math: --token: clamp(<min>rem, <rem> + <coef>vw, <max>rem)
//
// clamp()'s preferred branch is a CSS calc of a rem part (converts to px at
// 1rem = 16px) plus a vw part (vw is already "% of viewport width", so N vw
// at a viewport W px wide is N * (W / 100) px). The result is clamped between
// the min and max branches, each a plain rem length.
// ---------------------------------------------------------------------------
function lengthToPx(raw) {
  const m = /^(-?[\d.]+)(rem|px)$/.exec(raw.trim());
  if (!m) return null;
  const [, num, unit] = m;
  return unit === "rem" ? parseFloat(num) * 16 : parseFloat(num);
}

function parseClamp(value) {
  const m = /^clamp\(\s*([^,]+),\s*([^,]+),\s*([^,]+)\)$/.exec(value.trim());
  if (!m) return null;
  const [, minRaw, prefRaw, maxRaw] = m;
  const minPx = lengthToPx(minRaw);
  const maxPx = lengthToPx(maxRaw);
  const pm = /^(-?[\d.]+)rem\s*([+-])\s*(-?[\d.]+)vw$/.exec(prefRaw.trim());
  if (minPx == null || maxPx == null || !pm) return null;
  const [, remNum, sign, vwNum] = pm;
  const remPx = parseFloat(remNum) * 16;
  const vwCoef = (sign === "-" ? -1 : 1) * parseFloat(vwNum);
  return {
    minPx,
    maxPx,
    at(viewportPx) {
      const pref = remPx + vwCoef * (viewportPx / 100);
      return Math.min(maxPx, Math.max(minPx, pref));
    },
  };
}

function tokenValue(name) {
  return all.find((t) => t.name === name)?.value ?? null;
}

// Renders a size token (fixed rem/px, or fluid clamp()) at two reference
// viewport widths. Every px number here is computed from the live token
// value — nothing in this table is typed by hand.
function sizeAt360And1024(name) {
  const raw = tokenValue(name);
  if (raw == null) return { raw: null, px360: null, px1024: null };
  const c = parseClamp(raw);
  if (c) return { raw, px360: Math.round(c.at(360)), px1024: Math.round(c.at(1024)) };
  const px = lengthToPx(raw);
  return { raw, px360: px != null ? Math.round(px) : null, px1024: px != null ? Math.round(px) : null };
}

// ---- Display scale (website / marketing pages) -----------------------------
// --display-h1..h5 equal --font-size-h1..h5 at 1024px and above (per the
// brand spec); the 360px phone values are a draft pending a website audit.
const DISPLAY_KEYS = ["display-h1", "display-h2", "display-h3", "display-h4", "display-h5"];
export const displayScale = DISPLAY_KEYS.map((name) => {
  const { raw, px360, px1024 } = sizeAt360And1024(name);
  return { name, cssVar: `--${name}`, label: name.replace("display-", ""), raw, px360, px1024 };
});

// ---- Document scale (roadbooks, proposals, apps, print) ---------------------
// Per-style metadata (used-for description, typeface) is authored spec from
// the brand source text — tokens.css has no per-style font-family variable to
// read it from. Sizes, line heights, and weight ARE read from tokens via
