// Loads the live brand tokens at BUILD time by fetching the published
// tokens.css from the assets bucket and parsing the CSS custom properties.
// This keeps the guidelines site reading from the same single source of truth
// as every other app — no duplicated values.
//
// If the fetch fails (e.g. offline local dev), it falls back to a bundled
// snapshot at public/brand/tokens.css so the build never hard-breaks — but it
// logs a warning (below) so a stale fallback is never a silent failure.
//
// IMPORTANT: public/brand/tokens.css is a manually-maintained copy of the
// axelder/assets repo's public/brand/tokens.css. It is NOT regenerated by any
// script here. Whenever the published tokens change, refresh this snapshot by
// hand (copy the file from the assets repo) — otherwise local/offline builds
// will silently render old values.

import { readFileSync } from "node:fs";
import { resolve } from "node:path";

const TOKENS_URL =
  process.env.TOKENS_URL ?? "https://assets.cocolotravel.com/brand/tokens.css";

async function getCss() {
  // Try the live published tokens first (single source of truth).
  if (TOKENS_URL) {
    try {
      const res = await fetch(TOKENS_URL);
      if (res.ok) return { css: await res.text(), source: TOKENS_URL, usedFallback: false };
      console.warn(
        `[tokens] WARNING: fetching ${TOKENS_URL} returned HTTP ${res.status}. ` +
          `Falling back to the bundled snapshot at public/brand/tokens.css — ` +
          `that snapshot is hand-maintained and may be out of date.`,
      );
    } catch (err) {
      console.warn(
        `[tokens] WARNING: could not fetch ${TOKENS_URL} (${err.message}). ` +
          `Falling back to the bundled snapshot at public/brand/tokens.css — ` +
          `that snapshot is hand-maintained and may be out of date.`,
      );
    }
  }
  // Fallback: the snapshot bundled at public/brand/tokens.css, resolved from
  // the project root (process.cwd()) so it works regardless of where Astro
  // places the compiled module.
  const css = readFileSync(resolve(process.cwd(), "public/brand/tokens.css"), "utf8");
  return { css, source: "public/brand/tokens.css (bundled fallback)", usedFallback: true };
}

// Parse `--name: value;` declarations into {name, value} pairs.
function parseVars(css) {
  const out = [];
  const re = /--([a-z0-9-]+)\s*:\s*([^;]+);/gi;
  let m;
  while ((m = re.exec(css)) !== null) {
    out.push({ name: m[1].trim(), value: m[2].trim() });
  }
  return out;
}

// Pull the `@media print { :root { ... } }` block out on its own, so its
// declarations (print-only pt overrides) don't collide with the screen
// values of the same name parsed from the main :root block(s).
function splitPrintBlock(css) {
  const m = /@media\s+print\s*\{\s*:root\s*\{([^}]*)\}\s*\}/i.exec(css);
  if (!m) return { screenCss: css, printVars: [] };
  const screenCss = css.slice(0, m.index) + css.slice(m.index + m[0].length);
  return { screenCss, printVars: parseVars(m[1]) };
}

const { css: rawCss, source: tokenSource, usedFallback } = await getCss();
const { screenCss, printVars } = splitPrintBlock(rawCss);
const all = parseVars(screenCss);
const print = printVars;

// No silent failure: if whatever source we ended up with (live or fallback)
// doesn't have the tokens the new site sections depend on, fail the build
// loudly instead of rendering blank/undefined values.
const REQUIRED = ["doc-title", "display-h1", "tap-target-min"];
const missingRequired = REQUIRED.filter((name) => !all.some((t) => t.name === name));
if (missingRequired.length) {
  throw new Error(
    `[tokens] Build failed: the token source in use (${tokenSource}) is missing ` +
      `required token(s): ${missingRequired.map((n) => `--${n}`).join(", ")}. ` +
      `Refresh public/brand/tokens.css from the assets repo, or check TOKENS_URL.`,
  );
}

// Categorize by prefix so each page can render the right group.
// Two tiers: semantic tokens (background/text/border — what code should use)
// and brand primitives (the palette itself, group "brand").
const GROUP_ORDER = ["background", "text", "border", "brand"];
const GROUP_LABELS = {
  background: "Background",
  text: "Text",
  border: "Border",
  brand: "Brand primitives",
};

export const colors = all
  .filter((t) => t.name.startsWith("color-"))
  .map((t) => ({
    ...t,
    // color-background-primary -> group "background", label "primary"
    group: t.name.split("-")[1] ?? "",
    label: t.name.split("-").slice(2).join(" ") || t.name,
    cssVar: `--${t.name}`,
  }))
  .sort((a, b) => GROUP_ORDER.indexOf(a.group) - GROUP_ORDER.indexOf(b.group));

export function groupLabel(group) {
  return GROUP_LABELS[group] ?? group;
}

export const typographySizes = all
  .filter((t) => t.name.startsWith("font-size-"))
  .map((t) => ({ ...t, label: t.name.replace("font-size-", ""), cssVar: `--${t.name}` }));

export const typographyFamilies = all
  .filter((t) => t.name.startsWith("font-style-"))
  .map((t) => ({ ...t, label: t.name.replace("font-style-", ""), cssVar: `--${t.name}` }));

export const typographyWeights = all
  .filter((t) => t.name.startsWith("font-weights-"))
  .map((t) => ({ ...t, label: t.name.replace("font-weights-", ""), cssVar: `--${t.name}` }));

// Look up a resolved weight value by its token label (e.g. "bold" -> 700),
// so display tables can reference the live weight instead of typing a number.
function weightValue(label) {
  const t = typographyWeights.find((w) => w.label === label);
  return t ? t.value : null;
}

